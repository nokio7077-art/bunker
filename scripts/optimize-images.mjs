// Run with ffmpeg installed. Original PNGs stay intact; content hashes make caching safe.
import { readFileSync, writeFileSync, renameSync, readdirSync, unlinkSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { disasterImages } from '../public/card-images.js';
function compress(src){
 const path='public'+src, temp=path+'.tmp.webp';
 const result=spawnSync('ffmpeg',['-y','-hide_banner','-loglevel','error','-i',path,'-c:v','libwebp','-quality','90','-compression_level','6',temp]);
 if(result.status!==0)throw new Error(result.stderr.toString());
 const hash=createHash('sha256').update(readFileSync(temp)).digest('hex').slice(0,12);
 const dest=src.replace('.png',`.${hash}.webp`);renameSync(temp,'public'+dest);return dest;
}
for(const image of Object.values(disasterImages))image.webp=compress(image.src);
const landscapeImage=compress('/images/ui/bunker-landscape.png');
writeFileSync('public/card-images.js',`// Original artwork plus optimized, content-addressed copies.\nexport const disasterImages = ${JSON.stringify(disasterImages,null,2)};\nexport const landscapeImage = ${JSON.stringify(landscapeImage)};\n\nexport function disasterImageFor(disaster) {\n if (!disaster || Array.isArray(disaster)) return null;\n return Object.hasOwn(disasterImages, disaster.id) ? disasterImages[disaster.id] : null;\n}\n`);
const css=readFileSync('public/theme.css','utf8').replace(/\/images\/ui\/bunker-landscape(?:\.[a-f0-9]+)?\.(?:png|webp)/g,landscapeImage);writeFileSync('public/theme.css',css);
// Remove only stale optimized copies generated by this script.
const keep=new Set([landscapeImage,...Object.values(disasterImages).map(x=>x.webp)]);
for(const dir of ['/images/ui','/images/cards/disasters'])for(const name of readdirSync('public'+dir)){const path=dir+'/'+name;if(/\.[a-f0-9]{12}\.webp$/.test(name)&&!keep.has(path))unlinkSync('public'+path);}
console.log('Optimized 23 cards and landscape, originals preserved.');
